export function useSiteLocale() {
  const preference = useCookie('devportfolio-locale', {
    maxAge: 60 * 60 * 24 * 365,
    sameSite: 'lax'
  })

  const acceptLanguage = import.meta.server
    ? useRequestHeaders(['accept-language'])['accept-language'] || ''
    : ''

  const locale = useState('devportfolio-locale', () => {
    if (preference.value === 'en' || preference.value === 'fr') {
      return preference.value
    }

    const supportedLanguage = acceptLanguage
      .split(',')
      .map((language) => language.split(';')[0].trim().toLowerCase())
      .find((language) => language.startsWith('en') || language.startsWith('fr'))

    return supportedLanguage && supportedLanguage.startsWith('en') ? 'en' : 'fr'
  })

  const setLocale = (language) => {
    if (language !== 'en' && language !== 'fr') {
      throw new Error(`Unsupported language: ${language}`)
    }

    locale.value = language
    preference.value = language
  }

  const detectBrowserLocale = () => {
    if (preference.value === 'en' || preference.value === 'fr') {
      return
    }

    const supportedLanguage = navigator.languages
      .map((language) => language.toLowerCase())
      .find((language) => language.startsWith('en') || language.startsWith('fr'))

    if (supportedLanguage) {
      locale.value = supportedLanguage.startsWith('en') ? 'en' : 'fr'
    }
  }

  const t = (frenchText) => {
    if (locale.value !== 'en') {
      return frenchText
    }

    return englishTranslations[frenchText] || frenchText
  }

  return { locale, setLocale, detectBrowserLocale, t }
}
